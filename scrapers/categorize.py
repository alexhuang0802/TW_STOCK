def categorize(product_name: str) -> str:
    """根據商品名稱自動分類（含口味 vs 形態的歧義處理）"""
    if not product_name:
        return '其他'

    name = product_name.lower()

    # 第一步：檢查有沒有「形態詞」命中（這些直接決定分類，優先權最高）
    for cat, forms in FORM_OVERRIDES.items():
        for form in forms:
            if form.lower() in name:
                return cat

    # 第二步：正常的關鍵字匹配
    for category, keywords in CATEGORY_RULES:
        for kw in keywords:
            if kw.lower() in name:
                return category

    return '其他'


def categorize_promotions(promotions: list) -> list:
    """幫所有商品加上分類"""
    for p in promotions:
        if p.get('type') == 'product':
            # 如果已有分類且不是空的，保留原分類
            existing = p.get('category', '')
            if not existing or existing == '其他':
                # 用標題（不含優惠描述部分）來分類
                title = p.get('title', '')
                # 去掉 "— 買一送一" 之類的後綴
                name = title.split(' — ')[0] if ' — ' in title else title
                p['category'] = categorize(name)
    return promotions
